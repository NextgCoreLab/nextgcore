//! NextGCore NGAP codec generated from the TS 38.413 ASN.1 (#417, stage 1)
//!
//! Every type here is produced at build time from `asn/ngap-17.9.asn` by the
//! same forked `asn1-compiler` nextgsim uses (NextgCoreLab/asn1-codegen), with
//! the APER codec. The root
//! CHOICE therefore carries its key structurally:
//!
//! ```text
//! pub enum NGAP_PDU {
//!     #[asn(key = 0, ...)] InitiatingMessage(..),
//!     #[asn(key = 1, ...)] SuccessfulOutcome(..),
//!     #[asn(key = 2, ...)] UnsuccessfulOutcome(..),
//! }
//! ```
//!
//! So a PDU whose byte 0 is not the CHOICE index cannot be produced at all. With
//! a hand-written codec that is only true while someone keeps asserting it.
//!
//! Stage 1 added this crate with no call sites. Stage 2 moved amfd's NG Setup
//! Response and NG Setup Failure encoders. Stage 3 moved the NG Setup Request
//! DECODE, on [`decode_with_unknown_ies`]. Stage 4 moved the UE Context Release
//! family. Stage 5 moved the PDU Session Resource Release Command encode and
//! Response decode, and added [`encode_contained`] / [`decode_contained`] for
//! the `OCTET STRING (CONTAINING ...)` transfer containers the PDU session
//! families carry. Stage 6 moved the PDU Session Resource Setup Request encode
//! and Response decode, with the Setup Request and Response transfers, and
//! added [`decode_contained_with_unknown_ies`]. Everything else still goes
//! through `nextgcore-ngap` and `nextgcore-asn1c`'s `ngap` module.
//!
//! The forked codec this crate is generated by (NextgCoreLab/asn1-codegen,
//! pinned by rev in the workspace `src/Cargo.toml`) enforces the SIZE bounds of a
//! SEQUENCE OF on encode (nextgsim #212) and encodes and decodes ENUMERATED
//! extension values such as radioNetwork 45/46 (nextgsim #213). Its default
//! [`decode`] still fails the whole PDU on an IE id outside the schema; the
//! opt-in [`decode_with_unknown_ies`] (nextgsim #214) skips such an IE and hands
//! it back with its criticality, so the receiver can apply TS 38.413 §10.3.4.

/// The generated NGAP types. Names follow the ASN.1 with hyphens mapped to
/// underscores (`NGAP-PDU` is [`generated::NGAP_PDU`]), so the usual naming
/// lints do not apply.
#[allow(
    missing_docs,
    clippy::all,
    clippy::pedantic,
    clippy::nursery,
    unused,
    non_camel_case_types,
    non_snake_case
)]
pub mod generated {
    include!(concat!(env!("OUT_DIR"), "/ngap.rs"));
}

pub use generated::NGAP_PDU;

/// Decode one APER-encoded NGAP PDU.
pub fn decode(bytes: &[u8]) -> Result<NGAP_PDU, asn1_codecs::PerCodecError> {
    use asn1_codecs::aper::AperCodec;
    let mut data = asn1_codecs::PerCodecData::from_slice_aper(bytes);
    NGAP_PDU::aper_decode(&mut data)
}

/// A protocol IE (or protocol extension) whose id the schema has no entry for,
/// skipped by [`decode_with_unknown_ies`] instead of failing the decode.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnknownIe {
    /// The ProtocolIE-ID (or ProtocolExtensionID) as received.
    pub id: i128,
    /// Its `Criticality` index as sent -- 0 = reject, 1 = ignore, 2 = notify --
    /// or `None` if the container carries none. Every NGAP IE container does.
    pub criticality: Option<u8>,
    /// The IE value's octets, exactly as framed on the wire.
    pub value: Vec<u8>,
}

/// Decode one APER-encoded NGAP PDU, skipping protocol IEs whose id the schema
/// does not know and returning them alongside the PDU (TS 38.413 §10.3.4).
///
/// The rest of the message decodes as if the unknown IEs were absent. The
/// caller MUST inspect their criticality: an unknown IE marked `reject` still
/// means the procedure is to be rejected. An unknown id is only skippable as an
/// entry of a protocol-IE or extension container; anywhere else -- an unknown
/// procedure code, for one -- the decode still fails.
pub fn decode_with_unknown_ies(
    bytes: &[u8],
) -> Result<(NGAP_PDU, Vec<UnknownIe>), asn1_codecs::PerCodecError> {
    use asn1_codecs::aper::AperCodec;
    let mut data = asn1_codecs::PerCodecData::from_slice_aper(bytes);
    data.set_skip_unknown_open_types(true);
    let pdu = NGAP_PDU::aper_decode(&mut data)?;
    Ok((pdu, take_unknown(&mut data)))
}

/// Encode one NGAP PDU as APER.
pub fn encode(pdu: &NGAP_PDU) -> Result<Vec<u8>, asn1_codecs::PerCodecError> {
    use asn1_codecs::aper::AperCodec;
    let mut data = asn1_codecs::PerCodecData::new_aper();
    pdu.aper_encode(&mut data)?;
    Ok(data.into_bytes())
}

/// Encode `value` as the contents of an `OCTET STRING (CONTAINING ...)`, the
/// shape every NGAP SMF-to-gNB transfer travels in (the
/// `PDUSessionResource*Transfer` containers, TS 38.413 §9.3.4).
///
/// The contents are a complete APER encoding of their own, padded to an octet
/// boundary. Every NGAP transfer is an extensible SEQUENCE, so its encoding is
/// at least the extension bit: even a transfer whose every member is optional
/// and absent (a bare PDUSessionResourceReleaseResponseTransfer) is one zero
/// octet, never empty.
pub fn encode_contained<T: asn1_codecs::aper::AperCodec>(
    value: &T,
) -> Result<Vec<u8>, asn1_codecs::PerCodecError> {
    let mut data = asn1_codecs::PerCodecData::new_aper();
    value.aper_encode(&mut data)?;
    Ok(data.into_bytes())
}

/// Decode the contents of an `OCTET STRING (CONTAINING T)` -- the inverse of
/// [`encode_contained`]. The trailing padding of the octet-aligned contents is
/// not read.
pub fn decode_contained<T: asn1_codecs::aper::AperCodec>(
    bytes: &[u8],
) -> Result<T::Output, asn1_codecs::PerCodecError> {
    let mut data = asn1_codecs::PerCodecData::from_slice_aper(bytes);
    T::aper_decode(&mut data)
}

/// [`decode_contained`], skipping protocol IEs and protocol extensions whose id
/// the schema does not know and returning them alongside the value -- what
/// [`decode_with_unknown_ies`] does for a whole PDU, for a transfer container.
///
/// A transfer is the SMF's to interpret, so a receiver that only inspects it
/// (the AMF logging the gNB's DL tunnel) can drop the unknown IEs; one that
/// acts on it MUST still apply their criticality.
pub fn decode_contained_with_unknown_ies<T: asn1_codecs::aper::AperCodec>(
    bytes: &[u8],
) -> Result<(T::Output, Vec<UnknownIe>), asn1_codecs::PerCodecError> {
    let mut data = asn1_codecs::PerCodecData::from_slice_aper(bytes);
    data.set_skip_unknown_open_types(true);
    let value = T::aper_decode(&mut data)?;
    Ok((value, take_unknown(&mut data)))
}

/// The open types `data` skipped, as [`UnknownIe`]s.
fn take_unknown(data: &mut asn1_codecs::PerCodecData) -> Vec<UnknownIe> {
    data.take_unknown_open_types()
        .into_iter()
        .map(|u| UnknownIe {
            id: u.key,
            criticality: u.criticality.and_then(|c| u8::try_from(c).ok()),
            value: u.value,
        })
        .collect()
}

